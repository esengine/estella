/**
 * Flags the generated C must be compiled with. Not advice: `-ffp-contract=off`
 * is load-bearing, and a build that omits it will disagree with the interpreter
 * in the last bit of a multiply-add and be very hard to explain.
 */
export const CFLAGS: readonly string[] = [
    '-std=c11', '-O2', '-ffp-contract=off', '-fexcess-precision=standard',
];

/**
 * What linking one of these into a wasm module takes. Load-bearing, not taste:
 * the module owns no memory and has no entry, and the memory it is handed is
 * the ENGINE's — which grows, so one declaring a smaller maximum does not run
 * slower, it fails to instantiate with a LinkError.
 */
export const WASM_LINK_FLAGS: readonly string[] = [
    '--no-entry', '-sSTANDALONE_WASM', '-sIMPORTED_MEMORY',
    '-sALLOW_MEMORY_GROWTH=1', '-sERROR_ON_UNDEFINED_SYMBOLS=1',
];

/** The odd constant the width is multiplied by before it is folded in. */
export const ADDR_MIX = '0x9e3779b97f4a7c15';

export interface CModule {
    /** `estella_abi.h` — the contract's C side, and the only thing the code calls. */
    readonly header: string;
    /**
     * `estella_offsets.h` — where each field this program touches lives, from
     * EHT. Its own header rather than part of the source, because the engine
     * side has to assert against the SAME numbers: an `offsetof` that disagrees
     * with one of these is a read of a different field.
     */
    readonly offsets: string;
    /**
     * The translation unit: module functions and systems, and NOTHING else. A
     * module that shares the engine's memory must have no data section — a
     * static of its own is written at a link-time address the engine already
     * owns, which silently overwrites whatever is there.
     */
    readonly source: string;
    /**
     * The handshake constant and the declaration table, as a second translation
     * unit. A host that links against the engine reads them out of the artifact;
     * a host that loads the wasm reads the manifest instead, and must not
     * compile this.
     */
    readonly decls: string;
    /** Exported symbols, one per compiled system. */
    readonly symbols: readonly string[];
    /**
     * The handshake: what this module baked in about the ENGINE and about the
     * PROJECT, each so a loader can say which one moved.
     */
    readonly handshake: { readonly engineAbi: string; readonly projectShapes: string };
}

