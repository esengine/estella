/**
 * Emit C for the given systems. The caller decides which — `verifySystem` has to
 * have passed first, because this lowering is total over VALID EIR and its
 * reaction to invalid EIR is to throw, which is the right reaction to a compiler
 * bug and the wrong one to a source file outside the subset.
 */
export function emitC(module: EirModule, layout: AbiLayout, systems: readonly EirSystem[]): CModule {
    const offsets = new Map<string, number>();
    const plans = systems.map((s) => planFor(s));
    const bodies: string[] = [];

    // Module functions first: a system may call one, and C wants it declared
    // before the call. Only the ones still reachable after the inliner ran are
    // emitted, because an unreferenced static would warn.
    for (const name of calledFns(module, systems)) {
        const e = new Emitter(layout, offsets, null);
        e.fn(module.fns.get(name)!);
        bodies.push(e.text);
    }
    systems.forEach((sys, i) => {
        const e = new Emitter(layout, offsets, plans[i]!);
        e.system(sys);
        bodies.push(e.text);
    });

    const manifest = emitManifest(systems, plans);
    const handshake = abiHandshake(module.comps, plans);
    const macros = [...offsets].sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, v]) => `#define ${k} ${v}u`);
    const offsetsHeader = [
        '/* GENERATED by @estella/compiler — do not edit. */',
        '/* Field offsets from EHT, for the systems this program compiled. The',
        '   engine side asserts its own offsetof against these: a disagreement is',
        '   a read of a DIFFERENT FIELD, not an error. */',
        '#ifndef ESTELLA_OFFSETS_H',
        '#define ESTELLA_OFFSETS_H',
        '',
        ...macros,
        '',
        '#endif /* ESTELLA_OFFSETS_H */',
        '',
    ].join('\n');
    const source = [
        '/* GENERATED by @estella/compiler — do not edit. */',
        '/* This file calls the engine zero times, and holds no data of its own. */',
        '#include "estella_abi.h"',
        '#include "estella_offsets.h"',
        '',
        ...bodies,
    ].join('\n');
    const decls = [
        '/* GENERATED by @estella/compiler — do not edit. */',
        '/* The static half: what this module is, for a host that reads it out of',
        '   the artifact rather than out of a manifest beside it. Separate because',
        '   a wasm module sharing the ENGINE\'s memory must carry no data section —',
        '   its bytes would land at a link-time address the engine already owns. */',
        '#include "estella_abi.h"',
        '',
        '/* What this module baked in about the engine it was built for. A',
        '   host compares before it maps anything — a mismatch is not a wrong',
        '   answer, it is a read of a different field. The address width belongs',
        '   to the MACHINE, so it mixes in here rather than in the compiler and a',
        '   32-bit artifact cannot load into a 64-bit host. */',
        `#define ES_ABI_ENGINE_DIGEST 0x${handshake.engineAbi}ULL`,
        'const uint64_t es_abi_hash =',
        `    ES_ABI_ENGINE_DIGEST ^ (${ADDR_MIX}ULL * (uint64_t)sizeof(es_addr_t));`,
        '',
        ...systems.map((s) => `void ${cSymbol(s.name)}(es_addr_t es_ctx);`),
        '',
        ...manifest,
    ].join('\n');

    return {
        header: RUNTIME_H,
        offsets: offsetsHeader,
        source,
        decls,
        symbols: systems.map((s) => cSymbol(s.name)),
        handshake,
    };
}

/**
 * The table a host walks to call these systems: each one's symbol, and the
 * component and resource NAMES its ctx tables have to be filled from. Without it
 * every host writes the same list a second time, and the second list is the one
 * that goes stale.
 */
function emitManifest(systems: readonly EirSystem[], plans: readonly SysPlan[]): string[] {
    const out: string[] = ['/* The systems in this file, and what each one needs filled in. */'];
    const rows: string[] = [];
    systems.forEach((sys, i) => {
        const plan = plans[i]!;
        const tag = cSymbol(sys.name);
        plan.queries.forEach((args, k) => {
            out.push(`static const char *const ${tag}_q${k}_comps[] = { `
                + `${args.map((a) => JSON.stringify(a.comp)).join(', ')} };`);
            out.push(`static const unsigned char ${tag}_q${k}_mut[] = { `
                + `${args.map((a) => (a.mut ? '1u' : '0u')).join(', ')} };`);
        });
        if (plan.queries.length > 0) {
            const entries = plan.queries.map((args, k) =>
                `{ ${tag}_q${k}_comps, ${tag}_q${k}_mut, ${args.length}u }`);
            out.push(`static const EsQueryDecl ${tag}_queries[] = { ${entries.join(', ')} };`);
        }
        if (plan.resources.length > 0) {
            out.push(`static const char *const ${tag}_resources[] = { `
                + `${plan.resources.map((r) => JSON.stringify(r.name)).join(', ')} };`);
            out.push(`static const unsigned char ${tag}_resources_mut[] = { `
                + `${plan.resources.map((r) => (r.mut ? '1u' : '0u')).join(', ')} };`);
        }
        // C has no zero-length array, so an empty table is a null pointer and a
        // count of zero — which is also what a host would check anyway.
        rows.push(`    { ${JSON.stringify(sys.name)}, ${tag}, `
            + `${plan.queries.length > 0 ? `${tag}_queries` : 'NULL'}, `
            + `${plan.resources.length > 0 ? `${tag}_resources` : 'NULL'}, `
            + `${plan.resources.length > 0 ? `${tag}_resources_mut` : 'NULL'}, `
            + `${plan.queries.length}u, ${plan.resources.length}u },`);
    });
    out.push('');
    out.push('const EsSystemDecl es_systems[] = {');
    out.push(...rows);
    out.push('};');
    out.push(`const uint32_t es_system_count = ${systems.length}u;`);
    out.push('');
    return out;
}

/** Module functions still called after the inliner ran, in declaration order. */
function calledFns(module: EirModule, systems: readonly EirSystem[]): string[] {
    const want = new Set<string>();
    const visitExpr = (e: Expr): void => {
        switch (e.e) {
            case 'call':
                if (e.target.k === 'fn' && !want.has(e.target.name)) {
                    want.add(e.target.name);
                    const def = module.fns.get(e.target.name);
                    if (def) visit(def.body);
                }
                for (const a of e.args) visitExpr(a);
                break;
            case 'bin': case 'logic': visitExpr(e.l); visitExpr(e.r); break;
            case 'neg': case 'not': visitExpr(e.v); break;
            case 'select': visitExpr(e.cond); visitExpr(e.then); visitExpr(e.otherwise); break;
            default: break;
        }
    };
    const visit = (stmts: readonly Stmt[]): void => {
        for (const s of stmts) {
            switch (s.s) {
                case 'let': case 'assign': visitExpr(s.value); break;
                case 'return': if (s.value) visitExpr(s.value); break;
                case 'emit': for (const a of s.args) visitExpr(a); break;
                case 'if': visitExpr(s.cond); visit(s.then); visit(s.otherwise); break;
                case 'rowLoop': visit(s.body); break;
            }
        }
    };
    for (const sys of systems) visit(sys.body);
    // Declaration order, so a helper that calls a helper is defined first.
    return [...module.fns.keys()].filter((n) => want.has(n));
}
