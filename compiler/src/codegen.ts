/**
 * @file    codegen.ts
 * @brief   EIR -> C, against the SysCtx contract (docs/REARCH_AOT.md §10 Stage 2).
 *
 * @details The backend emits C rather than LLVM IR, and the reason is in §17:
 *          the LLVM half is a solved problem someone else maintains, and one C
 *          output serves clang for aarch64 and emcc for wasm at once. What is
 *          NOT solved anywhere is the half above it — EIR, and this lowering.
 *
 *          Two properties are the whole point, and both are visible in the
 *          output rather than asserted about it:
 *
 *          - **Zero calls.** A generated system's only external names are the
 *            static inlines in the runtime header. That is §6.5's empty import
 *            section, arrived at by construction rather than by trimming.
 *          - **Loads at constant offsets.** Every component field is
 *            `es_f32(base + ES_OFF_Comp_field)`, and the offset came from EHT.
 *            The offsets are macros so a debugger and a reader see the name.
 *
 *          Bit-for-bit agreement with node is a REQUIREMENT, not an aspiration,
 *          because the differential pixel gate compares frames. Three things
 *          here exist only for it: the Math shims (C's library disagrees with
 *          ECMAScript about `round`, `min` and `max` at zero and at ties), the
 *          storage width chosen by the shape rather than by the value, and
 *          `-ffp-contract=off` in CFLAGS — a fused multiply-add is more accurate
 *          than what JS computes, and more accurate is still different.
 */
import {
    CMD_DESPAWN, CMD_REMOVE, CMD_WORDS, QUERYROWS_WORDS,
    abiHash, planFor,
    type AbiLayout, type FieldOffsets, type Leaf, type SysPlan,
} from './abi';
import {
    BOOL, F64,
    type EirFn, type EirModule, type EirSystem, type EirType, type Expr, type Local,
    type MathFn, type Place, type Stmt,
} from './eir';

/**
 * Flags the generated C must be compiled with. Not advice: `-ffp-contract=off`
 * is load-bearing, and a build that omits it will disagree with the interpreter
 * in the last bit of a multiply-add and be very hard to explain.
 */
export const CFLAGS: readonly string[] = [
    '-std=c11', '-O2', '-ffp-contract=off', '-fexcess-precision=standard',
];

export interface CModule {
    /** `estella_abi.h` — the contract's C side, and the only thing the code calls. */
    readonly header: string;
    /** The translation unit: offsets, module functions, systems. */
    readonly source: string;
    /** Exported symbols, one per compiled system. */
    readonly symbols: readonly string[];
    /** The §2.5 handshake constant, also emitted into the source. */
    readonly hash: string;
}

// =============================================================================
// the runtime header — memory access, and the Math ECMAScript actually specifies
// =============================================================================

/**
 * Everything the generated code is allowed to reach. All of it is `static
 * inline`, so the object file has no undefined symbol and the wasm has no
 * import — §6.5 holds because there was never anything to import.
 */
export const RUNTIME_H = `/* GENERATED by @estella/compiler — do not edit. */
/* The Estella ABI, C side. docs/REARCH_AOT_ABI.md */
#ifndef ESTELLA_ABI_H
#define ESTELLA_ABI_H

#include <stdint.h>
#include <string.h>
#include <math.h>

/* A fused multiply-add is MORE accurate than the double rounding JS does, and
   more accurate is still a different number. GCC does not implement this pragma
   and warns about it, so the flag in CFLAGS is the one that has to be there;
   this is belt and braces for the compiler that does honour it. */
#if defined(__clang__)
#pragma STDC FP_CONTRACT OFF
#endif

/* An address in the ABI is a u32 offset into one linear memory. On wasm that
   memory starts at zero, so the offset already IS the pointer; natively the
   host owns a block and hands us its base. Same offsets either way — which is
   what lets one emitted source serve both back ends. */
#if defined(__wasm__)
#define ES_MEM ((unsigned char *)0)
#else
extern unsigned char *es_memory;
#define ES_MEM es_memory
#endif

/* memcpy, not a cast: the image is a byte block, and a u32 read through an
   aligned pointer is undefined if the host ever hands us an odd base. */
static inline uint32_t es_u32(uint32_t a) { uint32_t v; memcpy(&v, ES_MEM + a, 4); return v; }
static inline void es_set_u32(uint32_t a, uint32_t v) { memcpy(ES_MEM + a, &v, 4); }
static inline double es_f32(uint32_t a) { float v; memcpy(&v, ES_MEM + a, 4); return (double)v; }
static inline void es_set_f32(uint32_t a, double v) { float f = (float)v; memcpy(ES_MEM + a, &f, 4); }
static inline double es_f64(uint32_t a) { double v; memcpy(&v, ES_MEM + a, 8); return v; }
static inline void es_set_f64(uint32_t a, double v) { memcpy(ES_MEM + a, &v, 8); }

/* ---------------------------------------------------------------------------
   Math. Only the operations ECMAScript specifies EXACTLY are in the subset, but
   "exactly specified" is not the same as "what libm does" — three of them
   differ, and each difference is one bit of one pixel that would take a day to
   find. So each is written out rather than forwarded.
   --------------------------------------------------------------------------- */
static inline double es_abs(double x) { return fabs(x); }
static inline double es_floor(double x) { return floor(x); }
static inline double es_ceil(double x) { return ceil(x); }
static inline double es_trunc(double x) { return trunc(x); }
static inline double es_sqrt(double x) { return sqrt(x); }

/* Math.sign returns x itself for NaN and for both zeroes, so the sign of zero
   survives — and the sign of zero is a distinct bit pattern in the image. */
static inline double es_sign(double x) {
    if (isnan(x) || x == 0.0) return x;
    return x > 0.0 ? 1.0 : -1.0;
}

/* C's round() breaks ties AWAY from zero; ECMAScript breaks them toward +Inf.
   And floor(x + 0.5) — the usual fix — is wrong for the double just below 0.5,
   where the addition itself rounds up to 1. Subtracting the floor is exact for
   every finite x, so the comparison sees the true fraction. */
static inline double es_round(double x) {
    if (!isfinite(x) || x == 0.0) return x;
    double f = floor(x);
    double r = (x - f) < 0.5 ? f : f + 1.0;
    /* Math.round(-0.2) is -0, and -0 is not the same bytes as +0. */
    return (r == 0.0 && x < 0.0) ? -0.0 : r;
}

/* fmin/fmax return the non-NaN operand and are free to pick either zero;
   Math.min/max propagate NaN and distinguish -0 from +0. */
static inline double es_min(double a, double b) {
    if (isnan(a) || isnan(b)) return (double)NAN;
    if (a == b) return signbit(a) ? a : b;
    return a < b ? a : b;
}
static inline double es_max(double a, double b) {
    if (isnan(a) || isnan(b)) return (double)NAN;
    if (a == b) return signbit(a) ? b : a;
    return a > b ? a : b;
}

/* JS % on doubles is the truncated remainder, which is fmod. */
static inline double es_rem(double a, double b) { return fmod(a, b); }

#endif /* ESTELLA_ABI_H */
`;

