class Emitter {
    private readonly lines: string[] = [];
    private readonly byId = new Map<number, Local>();
    private readonly owners = new Map<number, string>();
    private depth = 0;

    constructor(
        private readonly layout: AbiLayout,
        /** Offset macros this translation unit turned out to need. */
        private readonly offsets: Map<string, number>,
        private readonly plan: SysPlan | null,
    ) {}

    get text(): string { return this.lines.join('\n'); }

    private bind(locals: readonly Local[]): void {
        for (const l of locals) {
            this.byId.set(l.id, l);
            if (l.type.k === 'comp' || l.type.k === 'res') this.owners.set(l.id, l.type.name);
        }
    }

    private line(indent: number, text: string): void {
        this.lines.push(`${'    '.repeat(indent)}${text}`);
    }

    private local(id: number): Local {
        const l = this.byId.get(id);
        if (!l) throw new Error(`codegen: local %${id} is used but never declared`);
        return l;
    }

    /** `base + ES_OFF_Comp_field` — one add against a constant, which is the point. */
    private address(base: Place, path: readonly string[]): { addr: string; leaf: Leaf } {
        if (base.p !== 'local') throw new Error('codegen: a field base must be a local');
        const owner = this.owners.get(base.id);
        if (!owner) throw new Error(`codegen: local %${base.id} owns no fields`);
        const shape: FieldOffsets | undefined =
            this.layout.comps.get(owner) ?? this.layout.resources.get(owner);
        const leaf = shape?.leaves.get(path.join('.'));
        if (!leaf) throw new Error(`codegen: '${owner}' has no field '${path.join('.')}'`);
        const macro = offsetMacro(owner, path);
        this.offsets.set(macro, leaf.byteOffset);
        return { addr: `${cName(this.local(base.id))} + ${macro}`, leaf };
    }

    /** Read a place; the result's C type is `cType(type)`. */
    private read(p: Place, type: EirType): string {
        if (p.p === 'local') return cName(this.local(p.id));
        const { addr, leaf } = this.address(p.base, p.path);
        const load = leaf.bits === 64 ? `es_f64(${addr})` : `es_f32(${addr})`;
        return coerce(load, F64, type);
    }

    /** An expression, parenthesised so composition never needs precedence rules. */
    expr(e: Expr): string {
        switch (e.e) {
            case 'const':
                return typeof e.value === 'boolean' ? (e.value ? '1' : '0') : num(e.value);
            case 'read':
                return this.read(e.place, e.type);
            case 'neg':
                return `(-${coerce(this.expr(e.v), e.v.type, F64)})`;
            case 'not':
                return `(!${coerce(this.expr(e.v), e.v.type, BOOL)})`;
            case 'logic':
                return `(${coerce(this.expr(e.l), e.l.type, BOOL)} ${e.op} `
                    + `${coerce(this.expr(e.r), e.r.type, BOOL)})`;
            case 'select':
                return `(${coerce(this.expr(e.cond), e.cond.type, BOOL)} ? `
                    + `${coerce(this.expr(e.then), e.then.type, e.type)} : `
                    + `${coerce(this.expr(e.otherwise), e.otherwise.type, e.type)})`;
            case 'bin': {
                const l = coerce(this.expr(e.l), e.l.type, F64);
                const r = coerce(this.expr(e.r), e.r.type, F64);
                // `%` is a call because C's % is integer-only; JS's is fmod.
                if (e.op === '%') return `es_rem(${l}, ${r})`;
                return `(${l} ${e.op} ${r})`;
            }
            case 'call': {
                const args = e.args.map((a) => coerce(this.expr(a), a.type, F64));
                if (e.target.k === 'math') return `${MATH_C[e.target.fn]}(${args.join(', ')})`;
                return `${cFn(e.target.name)}(${args.join(', ')})`;
            }
        }
    }

    stmts(list: readonly Stmt[], indent: number): void {
        for (const s of list) this.stmt(s, indent);
    }

    private stmt(s: Stmt, indent: number): void {
        switch (s.s) {
            case 'let': {
                const l = this.local(s.id);
                this.line(indent, `${cName(l)} = ${coerce(this.expr(s.value), s.value.type, l.type)};`);
                break;
            }
            case 'return':
                this.line(indent, `return ${this.expr(s.value)};`);
                break;
            case 'assign': {
                if (s.target.p === 'local') {
                    const l = this.local(s.target.id);
                    this.line(indent, `${cName(l)} = ${coerce(this.expr(s.value), s.value.type, l.type)};`);
                    break;
                }
                const { addr, leaf } = this.address(s.target.base, s.target.path);
                const store = leaf.bits === 64 ? 'es_set_f64' : 'es_set_f32';
                this.line(indent, `${store}(${addr}, ${coerce(this.expr(s.value), s.value.type, F64)});`);
                break;
            }
            case 'if': {
                this.line(indent, `if (${coerce(this.expr(s.cond), s.cond.type, BOOL)}) {`);
                this.stmts(s.then, indent + 1);
                if (s.otherwise.length > 0) {
                    this.line(indent, '} else {');
                    this.stmts(s.otherwise, indent + 1);
                }
                this.line(indent, '}');
                break;
            }
            case 'emit':
                this.emitCommand(s, indent);
                break;
            case 'rowLoop':
                this.rowLoop(s, indent);
                break;
        }
    }

    /**
     * A command is four words written into the host's buffer and a counter
     * bumped — no call, and nothing read back. The `cap` guard is the
     * contract's: §3 forbids writing past it, and the host is what sized it.
     */
    private emitCommand(s: Stmt & { s: 'emit' }, indent: number): void {
        const kind = s.record === 'despawn' ? CMD_DESPAWN : CMD_REMOVE;
        this.line(indent, 'if (es_cmd_n < es_cmd_cap) {');
        this.line(indent + 1, `const uint32_t es_at = es_cmd_buf + es_cmd_n * ${CMD_WORDS * 4}u;`);
        this.line(indent + 1, `es_set_u32(es_at, ${kind}u); /* ${s.record} */`);
        for (let i = 1; i < CMD_WORDS; i++) {
            const a = s.args[i - 1];
            const v = a ? coerce(this.expr(a), a.type, { k: 'entity' }) : '0u';
            this.line(indent + 1, `es_set_u32(es_at + ${i * 4}u, ${v});`);
        }
        this.line(indent + 1, 'es_cmd_n += 1u;');
        this.line(indent, '}');
    }

    /**
     * The op EIR exists to keep (§4.2): a strided walk of a packed row array.
     * One `es_u32` per component per row and no lookup — the host already did
     * the lookup once, in C++, which is where it is cheap.
     */
    private rowLoop(s: Stmt & { s: 'rowLoop' }, indent: number): void {
        if (s.query.p !== 'local') throw new Error('codegen: a rowLoop walks a query local');
        const slot = this.plan?.slots.get(s.query.id);
        if (!slot || slot.table !== 'query') throw new Error('codegen: that local is not a declared query');
        const q = this.plan!.queries[slot.slot]!;
        const d = this.depth++;
        const stride = 1 + q.length;
        const at = slot.slot * QUERYROWS_WORDS * 4;
        const reads = new Set<number>();
        readsOf(s.body, reads);
        this.line(indent, '{');
        this.line(indent + 1, `const uint32_t es_rows${d} = es_u32(es_queries + ${at}u);`);
        this.line(indent + 1, `const uint32_t es_n${d} = es_u32(es_queries + ${at + 4}u);`);
        this.line(indent + 1, `for (uint32_t es_i${d} = 0u; es_i${d} < es_n${d}; ++es_i${d}) {`);
        this.line(indent + 2, `const uint32_t es_row${d} = es_rows${d} + es_i${d} * ${stride * 4}u;`);
        if (s.entity !== null && reads.has(s.entity)) {
            this.line(indent + 2, `const uint32_t ${cName(this.local(s.entity))} = es_u32(es_row${d});`);
        }
        s.binds.forEach((id, i) => {
            // A bound component nobody reads is not loaded. The row is still
            // strided past it, because the row's shape is the query's, not the
            // body's — dropping the load is free, dropping the column is not.
            if (!reads.has(id)) return;
            this.line(indent + 2,
                `const uint32_t ${cName(this.local(id))} = es_u32(es_row${d} + ${(i + 1) * 4}u);`);
        });
        this.stmts(s.body, indent + 2);
        this.line(indent + 1, '}');
        this.line(indent, '}');
        this.depth--;
    }

    /** A module-level pure function: numbers in, one number out, no world. */
    fn(f: EirFn): void {
        this.bind([...f.params, ...f.locals]);
        const params = f.params.map((p) => `${cType(p.type)} ${cName(p)}`).join(', ');
        this.line(0, `static ${cType(f.ret)} ${cFn(f.name)}(${params || 'void'}) {`);
        this.declare(f.locals, null, 1);
        this.stmts(f.body, 1);
        this.line(0, '}');
        this.line(0, '');
    }

    /** `void es_sys_<Name>(uint32_t ctx)` — §2.1's one exported symbol. */
    system(sys: EirSystem): void {
        const plan = this.plan!;
        this.bind([...sys.params, ...sys.locals]);
        const reads = new Set<number>();
        readsOf(sys.body, reads);
        const bound = new Set<number>();
        loopBound(sys.body, bound);

        this.line(0, `void ${cSymbol(sys.name)}(uint32_t es_ctx) {`);
        if (plan.queries.length > 0) this.line(1, 'const uint32_t es_queries = es_u32(es_ctx);');
        const usesRes = sys.params.some((p) => plan.slots.get(p.id)!.table === 'res' && reads.has(p.id));
        if (usesRes) this.line(1, 'const uint32_t es_resources = es_u32(es_ctx + 4u);');
        const emits = hasEmit(sys.body);
        if (emits) {
            this.line(1, 'const uint32_t es_cmd_buf = es_u32(es_ctx + 8u);');
            this.line(1, 'const uint32_t es_cmd_cap = es_u32(es_ctx + 12u);');
            this.line(1, 'const uint32_t es_cmd_at = es_u32(es_ctx + 16u);');
            this.line(1, 'uint32_t es_cmd_n = es_u32(es_cmd_at);');
        }
        // A resource base is one indirection, resolved once at entry rather than
        // per row: the host already put the address in the table.
        for (const p of sys.params) {
            const slot = plan.slots.get(p.id)!;
            if (slot.table !== 'res' || !reads.has(p.id)) continue;
            this.line(1, `const uint32_t ${cName(p)} = es_u32(es_resources + ${slot.slot * 4}u);`);
        }
        this.declare(sys.locals.filter((l) => !bound.has(l.id)), reads, 1);
        this.stmts(sys.body, 1);
        if (emits) this.line(1, 'es_set_u32(es_cmd_at, es_cmd_n);');
        this.line(0, '}');
        this.line(0, '');
    }

    /**
     * Function-scope locals. A declared local nobody reads would draw a warning,
     * and a warning in generated code is a warning nobody will ever read — so it
     * is spelled `(void)` here rather than silenced at the compiler.
     */
    private declare(locals: readonly Local[], reads: ReadonlySet<number> | null, indent: number): void {
        for (const l of locals) {
            this.line(indent, `${cType(l.type)} ${cName(l)} = ${zeroOf(l.type)};`);
            if (reads && !reads.has(l.id)) this.line(indent, `(void)${cName(l)};`);
        }
    }
}

