/**
 * @file    workers.ts
 * @brief   The engine's job workers on a mini-game host: one packaged worker file that carries every kind, and the factory that talks to it.
 *
 * @details A mini-game host has workers, but not a browser's. A worker is a file in the package, under the directory `game.json` names
 *          (`"workers"`), started by path (`wx.createWorker`); a script's text cannot be one, and nothing may be evaluated. At most ONE may
 *          exist at a time. Its global is `worker` (`worker.onMessage`, `worker.postMessage`), there is no `self`, and before base library
 *          2.20.2 a message could only be a plain key-value object (no ArrayBuffer), so older hosts get no workers at all.
 *          (developers.weixin.qq.com/minigame/dev/api/worker/wx.createWorker.html, .../Worker.postMessage.html)
 *
 *          So the export writes one file, {@link miniGameWorkerFile}, holding each worker script the content needs, each run against a
 *          `self` of its own; and {@link miniGameWorkerFactory} starts that one worker and gives every pool its own channel through it,
 *          the jobs layer seeing a worker per pool. Every message is an envelope `{ __es: name, c: channel, d: message }`: the name says
 *          which script, the channel which pool (two pools of one script must not read each other's answers).
 *
 *          The worker can be taken by the system (an experimental worker on iOS under memory pressure): every pool is then told its worker
 *          failed, and the jobs layer does their jobs on the main thread, in turns of the frame's budget, from then on.
 *
 *          Both halves of the envelope are here, so the file and the factory cannot disagree.
 */
import { setJobWorkerFactory, type JobWorker, type JobWorkerFactory } from '../../runtime/jobs';

/** The directory `game.json` names as the workers' root, and the worker's entry file in the package. */
export const MINIGAME_WORKER_DIR = 'workers';
export const MINIGAME_WORKER_ENTRY = `${MINIGAME_WORKER_DIR}/index.js`;

/** The base library from which a worker message may be any data (an ArrayBuffer, a typed array): below it there are no workers. */
export const MINIGAME_WORKER_MIN_BASE_LIBRARY = '2.20.2';

/**
 * The text of the packaged worker: each script in `scripts` (name to its text, as the jobs layer starts it) under a dispatcher that gives
 * each channel its own `self`. A script asked for by a name it does not carry answers `lost`, so that pool is done on the main thread.
 *
 * The scripts are written for a browser worker: `self.onmessage`, `self.postMessage`, and `self.importScripts` as the test that they run
 * in a worker; importing throws here, since a mini-game worker loads nothing by URL. The export down-levels the whole file to the host's
 * syntax floor.
 */
export function miniGameWorkerFile(scripts: Readonly<Record<string, string>>): string {
    const factories = Object.entries(scripts)
        .map(([name, text]) => `factories[${JSON.stringify(name)}] = function (self) {\n${text}\n};`)
        .join('\n');
    return `'use strict';
// The engine's job workers, generated by the export: do not edit.
var factories = {};
${factories}
var scopes = {};
function scopeFor(name, channel) {
    return {
        onmessage: null,
        document: undefined,
        importScripts: function () { throw new Error('a mini-game worker cannot import scripts'); },
        postMessage: function (d) { worker.postMessage({ __es: name, c: channel, d: d }); }
    };
}
function envelope(res) {
    if (res && res.__es !== undefined) return res;
    if (res && res.data && res.data.__es !== undefined) return res.data;
    return null;
}
worker.onMessage(function (res) {
    var m = envelope(res);
    if (!m) return;
    var key = m.__es + ':' + m.c;
    if (m.end) { delete scopes[key]; return; }
    var s = scopes[key];
    if (!s) {
        var make = factories[m.__es];
        if (!make) {
            worker.postMessage({ __es: m.__es, c: m.c, d: { id: m.d && m.d.id, error: 'this package carries no ' + m.__es + ' worker', lost: true } });
            return;
        }
        s = scopes[key] = scopeFor(m.__es, m.c);
        make(s);
    }
    if (s.onmessage) s.onmessage({ data: m.d });
});
`;
}

/** What the factory needs of a host's worker. */
export interface MiniGameWorker {
    postMessage(message: unknown): void;
    onMessage(cb: (res: unknown) => void): void;
    terminate(): void;
    onProcessKilled?(cb: () => void): void;
    onError?(cb: (err: unknown) => void): void;
}

/** What the factory needs of a host's global. */
export interface MiniGameWorkerHost {
    createWorker?(scriptPath: string, options?: { useExperimentalWorker?: boolean }): MiniGameWorker;
    getSystemInfoSync?(): { SDKVersion?: string };
    getAppBaseInfo?(): { SDKVersion?: string };
}

/** Whether `version` is at least `floor`, both dotted numbers. */
export function versionAtLeast(version: string, floor: string): boolean {
    const a = version.split('.').map((n) => parseInt(n, 10) || 0), b = floor.split('.').map((n) => parseInt(n, 10) || 0);
    for (let i = 0; i < Math.max(a.length, b.length); i++) {
        const d = (a[i] ?? 0) - (b[i] ?? 0);
        if (d !== 0) return d > 0;
    }
    return true;
}

function baseLibrary(host: MiniGameWorkerHost): string | null {
    try {
        return host.getAppBaseInfo?.().SDKVersion ?? host.getSystemInfoSync?.().SDKVersion ?? null;
    } catch {
        return null;
    }
}

/**
 * Starts pools on the package's one worker: a pool for each kind in `carried`, each on a channel of its own, and none for a kind the
 * package does not carry or on a host whose base library is older than {@link MINIGAME_WORKER_MIN_BASE_LIBRARY} (an unknown one counts
 * as older). However many workers a pool asks for, it is given one.
 */
export function miniGameWorkerFactory(host: MiniGameWorkerHost, carried: readonly string[], entry = MINIGAME_WORKER_ENTRY): JobWorkerFactory {
    const kinds = new Set(carried);
    let real: MiniGameWorker | null = null;
    let broken = false;
    let nextChannel = 1;
    const channels = new Map<number, JobWorker>();
    const fail = (why: string): void => {
        broken = true;
        real = null;
        const told = [...channels.values()];
        channels.clear();
        for (const w of told) w.onerror?.({ message: why });
    };
    const start = (): MiniGameWorker | null => {
        if (real) return real;
        if (broken || typeof host.createWorker !== 'function') return null;
        let w: MiniGameWorker;
        try {
            // Experimental: several times faster on iOS, and the reason the host may take it back (onProcessKilled).
            w = host.createWorker(entry, { useExperimentalWorker: true });
        } catch {
            broken = true;
            return null;
        }
        w.onMessage((res) => {
            const m = (res && (res as { __es?: unknown }).__es !== undefined ? res : (res as { data?: unknown } | null)?.data) as
                { c?: number; d?: unknown } | undefined;
            if (!m || typeof m.c !== 'number') return;
            channels.get(m.c)?.onmessage?.({ data: m.d });
        });
        w.onProcessKilled?.(() => fail('the host took the worker back'));
        w.onError?.((err) => fail(String((err as { message?: string; errMsg?: string })?.message ?? (err as { errMsg?: string })?.errMsg ?? err)));
        real = w;
        return w;
    };
    return (_script, name) => {
        if (!kinds.has(name)) return null;
        const version = baseLibrary(host);
        if (!version || !versionAtLeast(version, MINIGAME_WORKER_MIN_BASE_LIBRARY)) return null;
        const w = start();
        if (!w) return null;
        const channel = nextChannel++;
        const pool: JobWorker = {
            onmessage: null,
            onerror: null,
            // No transfer list on this host: the data is copied.
            postMessage: (message) => { if (real === w) w.postMessage({ __es: name, c: channel, d: message }); },
            terminate: () => {
                if (!channels.delete(channel) || real !== w) return;
                w.postMessage({ __es: name, c: channel, end: true });
                // The last pool gone: the one worker the host allows is let go, for whoever starts one next.
                if (channels.size === 0) { w.terminate(); real = null; }
            },
        };
        channels.set(channel, pool);
        return [pool];
    };
}

/** Makes the jobs layer start its workers from the package's worker file, for the kinds the export put in it. */
export function installMiniGameWorkers(host: MiniGameWorkerHost | undefined, carried: readonly string[]): void {
    if (!host || carried.length === 0) return;
    setJobWorkerFactory(miniGameWorkerFactory(host, carried));
}
