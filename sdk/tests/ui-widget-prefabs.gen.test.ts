// Generates the built-in UI widget prefabs from the factories (single source)
// and verifies the captured tree. Writing the .esprefab files is the codegen;
// the assertions are the guard that the factory still round-trips to a prefab.
import { describe, it, expect, afterAll } from 'vitest';
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import type { World } from '../src/world';
import type { PrefabData } from '../src/prefab/types';
import { widgetToPrefab } from '../src/ui/widgets/toPrefab';
import { createButton } from '../src/ui/widgets/button';
import { createToggle } from '../src/ui/widgets/toggle';
import { createSlider } from '../src/ui/widgets/slider';
import { createProgress } from '../src/ui/widgets/progress';
import { createDropdown } from '../src/ui/widgets/dropdown';
import { spawnUIEntity } from '../src/ui/widgets/helpers';
import { UIMask, MaskMode } from '../src/ui/core/ui-mask';
import { Interactable, UIInteraction } from '../src/ui/input/interactable';
import { themeColors } from '../src/ui/theme/tokens';
import { px } from '../src/ui/core/dimension';

const OUT_DIR = resolve(__dirname, '../src/ui/widgets/prefabs');
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const noEvents = { on: () => {} } as any;
const c = themeColors();

function entityById(p: PrefabData, id: string) {
    return p.entities.find((e) => e.prefabEntityId === id)!;
}
function typesOf(p: PrefabData, id: string): string[] {
    return entityById(p, id).components.map((cc) => cc.type);
}

const GENERATED: Record<string, PrefabData> = {};

function generate(name: string, build: (w: World) => number): PrefabData {
    const prefab = widgetToPrefab(build, name);
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(resolve(OUT_DIR, `${name}.esprefab`), JSON.stringify(prefab, null, 2) + '\n');
    GENERATED[name] = prefab;
    return prefab;
}

// Emit the SDK-exported data module the editor's "Create → UI" menu instantiates.
afterAll(() => {
    const names = Object.keys(GENERATED);
    const body =
        '// AUTO-GENERATED by tests/ui-widget-prefabs.gen.test.ts — do not edit by hand.\n' +
        "import type { PrefabData } from '../../../prefab/types';\n\n" +
        `export const BUILTIN_UI_PREFABS: Record<string, PrefabData> = ${JSON.stringify(GENERATED, null, 2)};\n\n` +
        `export const BUILTIN_UI_WIDGET_NAMES = ${JSON.stringify(names)} as const;\n`;
    writeFileSync(resolve(OUT_DIR, 'generated.ts'), body);
});

describe('UI widget prefab codegen', () => {
    it('Button: factory → prefab captures the full clickable tree + label', () => {
        const prefab = generate('Button', (world) =>
            createButton({
                world, events: noEvents,
                node: { width: px(140), height: px(40) },
                states: {
                    normal: { color: c.control },
                    hover: { color: c.controlHover },
                    pressed: { color: c.controlActive },
                },
                text: { content: 'Button', color: c.onPrimary, fontSize: 14 },
            }) as unknown as number,
        );

        const root = typesOf(prefab, prefab.rootEntityId);
        expect(root).toEqual(expect.arrayContaining([
            'Transform', 'UINode', 'UIVisual', 'Interactable', 'UIInteraction', 'UIController', 'UIGear',
        ]));
        const rootEnt = entityById(prefab, prefab.rootEntityId);
        expect(rootEnt.children.length).toBe(1);
        const label = entityById(prefab, rootEnt.children[0]!);
        expect(label.components.map((x) => x.type)).toEqual(expect.arrayContaining(['UINode', 'Text']));
        expect(label.parent).toBe(prefab.rootEntityId);
    });

    it('Toggle: box + checkmark child', () => {
        const prefab = generate('Toggle', (world) =>
            createToggle({
                world, events: noEvents,
                node: { width: px(28), height: px(28) },
                background: { color: c.control },
                interactionStates: {
                    normal: { color: c.control }, hover: { color: c.controlHover }, pressed: { color: c.controlActive },
                },
                check: { color: c.primary }, isOn: true,
            }).entity as unknown as number,
        );
        expect(typesOf(prefab, prefab.rootEntityId)).toEqual(expect.arrayContaining(['UINode', 'Interactable', 'UIGear']));
        expect(entityById(prefab, prefab.rootEntityId).children.length).toBeGreaterThanOrEqual(1);
    });

    it('Slider: track + fill + handle', () => {
        const prefab = generate('Slider', (world) =>
            createSlider({
                world, node: { width: px(200), height: px(18) },
                min: 0, max: 100, step: 1, value: 50, handleWidth: 14,
            }).entity as unknown as number,
        );
        expect(entityById(prefab, prefab.rootEntityId).children.length).toBe(2);
    });

    it('Progress: track + fill', () => {
        const prefab = generate('Progress', (world) =>
            createProgress({
                world, node: { width: px(200), height: px(14) },
                fill: { color: c.primary }, value: 0.4,
            }).entity as unknown as number,
        );
        expect(entityById(prefab, prefab.rootEntityId).children.length).toBe(1);
    });

    it('Dropdown: button + label (popup lives outside the subtree)', () => {
        const prefab = generate('Dropdown', (world) =>
            createDropdown<string>({
                world, events: noEvents,
                node: { width: px(150), height: px(34) },
                options: ['One', 'Two', 'Three'], optionToLabel: (o) => o, optionHeight: 30,
            }).entity as unknown as number,
        );
        expect(typesOf(prefab, prefab.rootEntityId)).toEqual(expect.arrayContaining(['UINode', 'Interactable']));
    });

    it('ListView: a clipped viewport shell (items are populated by createListView in code)', () => {
        const prefab = generate('ListView', (world) => {
            // The serializable half of createListView: a sized viewport with a
            // Scissor mask + a hover hit-target, plus a placeholder label. Data and
            // item rows are runtime-only — wire them with createListView in code.
            const viewport = spawnUIEntity({
                world,
                node: { width: px(240), height: px(320) },
                visual: { color: c.control },
            });
            world.insert(viewport, UIMask, { enabled: true, mode: MaskMode.Scissor, maskTexture: 0, inverted: false });
            world.insert(viewport, Interactable, { enabled: true, blockRaycast: true, raycastTarget: true });
            world.insert(viewport, UIInteraction, { hovered: false, pressed: false, justPressed: false, justReleased: false });
            spawnUIEntity({
                world, parent: viewport,
                node: { fill: true },
                text: { content: 'List View', color: c.onPrimary, fontSize: 14 },
            });
            return viewport as unknown as number;
        });
        expect(typesOf(prefab, prefab.rootEntityId)).toEqual(expect.arrayContaining([
            'UINode', 'UIVisual', 'UIMask', 'Interactable',
        ]));
        expect(entityById(prefab, prefab.rootEntityId).children.length).toBe(1);
    });
});
